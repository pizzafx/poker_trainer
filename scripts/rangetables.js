// Builds the range tracker's tables (src/bots/rangetables.js) from simulated play of the current opponents:
//   prior[role][flop class][bin]      what a player holds on the flop, by what they did before it
//   trans[turn|river][event][from][to] how bins move when a card comes
//   lik[situation][action][bin]        how likely each bin is to take each action
// node scripts/rangetables.js [hands per seed, default 40000] [seeds, default 101,102,103,104] [table]
import fs from 'fs';
import { walk } from './rangelib.js';
import { RangeTrack, B, ROLES, FCLASS, EVENTS, NSIT, flopClass, eventOf, roleOf } from '../src/bots/rangetrack.js';

const HANDS = +(process.argv[2] || 40000);
const SEEDS = (process.argv[3] || '101,102,103,104').split(',').map(Number);
const TABLE = process.argv[4] || 'typical';
const z = (...d) => (d.length === 1 ? new Float64Array(d[0]) : Array.from({ length: d[0] }, () => z(...d.slice(1))));
const prior = z(ROLES, FCLASS, B);
const trans = z(2, EVENTS, B, B);
const lik = z(NSIT, 3, B);
const tr = new RangeTrack(null);
let points = 0;
for (const seed of SEEDS) {
  walk({
    seed,
    table: TABLE,
    hands: HANDS,
    trackers: [tr],
    noBelief: true,
    onFlop: ({ s, bins }) => {
      const fc = flopClass(s.board);
      for (let p = 0; p < s.n; p++) if (bins[p] >= 0) prior[roleOf(s, p)][fc][bins[p]]++;
    },
    onStreet: ({ s, prevBins, bins, len }) => {
      const ev = eventOf(s.board, len);
      for (let p = 0; p < s.n; p++) if (bins[p] >= 0 && prevBins[p] >= 0) trans[len - 4][ev][prevBins[p]][bins[p]]++;
    },
    onAct: ({ sit, e, bin }) => {
      lik[sit.key][RangeTrack.bucket(sit, e)][bin]++;
      points++;
    },
  });
}
// to probabilities
const round = (x) => +x.toFixed(4);
const priorP = prior.map((r) => r.map((h) => { const t = h.reduce((a, b) => a + b, 0); return Array.from(h, (x) => round((x + 0.5) / (t + 0.5 * B))); }));
const transP = trans.map((st) => st.map((ev) => ev.map((row, i) => { const t = row.reduce((a, b) => a + b, 0); return Array.from(row, (x, j) => round((x + (i === j ? 2 : 0)) / (t + 2))); })));
// P(action | bin, situation), shrunk toward the situation's overall action shares where a bin is thin
const likP = lik.map((acts) => {
  const tot = new Float64Array(B);
  let all = 0;
  const share = [0, 0, 0];
  for (let a = 0; a < 3; a++) for (let b = 0; b < B; b++) { tot[b] += acts[a][b]; share[a] += acts[a][b]; all += acts[a][b]; }
  return acts.map((row, a) => Array.from(row, (x, b) => round((x + 4 * (all ? share[a] / all : 1 / 3)) / (tot[b] + 4))));
});
const out = `// Generated by scripts/rangetables.js (${TABLE} table, ${SEEDS.length} x ${HANDS} hands, ${points} postflop actions). Do not edit.\nexport const RANGE_TABLES = ${JSON.stringify({ prior: priorP, trans: transP, lik: likP })};\n`;
fs.writeFileSync(new URL('../src/bots/rangetables.js', import.meta.url), out);
console.log(`written src/bots/rangetables.js: ${points} postflop actions, ${(out.length / 1024).toFixed(0)} KB`);
const thin = lik.filter((acts) => acts.reduce((a, r) => a + r.reduce((x, y) => x + y, 0), 0) < 500).length;
console.log(`situations with under 500 actions: ${thin} of ${NSIT}`);
