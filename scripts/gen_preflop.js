// Generates src/data/preflop.js: all-in equity of each of the 169 starting-hand classes
// against 1 random hand and against 3 random hands (Monte Carlo). Run: node scripts/gen_preflop.js

import { writeFileSync } from 'node:fs';
import { makeRng, makeCard } from '../src/engine/cards.js';
import { evaluate } from '../src/engine/evaluator.js';
import { classNames, classInfo } from '../src/engine/hands.js';

const rng = makeRng(20261110);
const SAMPLES = 40000;

function equity(hole, opponents) {
  const deck = [];
  for (let c = 0; c < 52; c++) if (c !== hole[0] && c !== hole[1]) deck.push(c);
  const need = opponents * 2 + 5;
  let share = 0;
  const seven = new Array(7);
  for (let t = 0; t < SAMPLES; t++) {
    for (let i = 0; i < need; i++) {
      const j = i + Math.floor(rng() * (deck.length - i));
      const tmp = deck[i];
      deck[i] = deck[j];
      deck[j] = tmp;
    }
    const b = opponents * 2;
    for (let i = 0; i < 5; i++) seven[2 + i] = deck[b + i];
    seven[0] = hole[0];
    seven[1] = hole[1];
    const mine = evaluate(seven);
    let best = -1;
    let ties = 0;
    for (let o = 0; o < opponents; o++) {
      seven[0] = deck[o * 2];
      seven[1] = deck[o * 2 + 1];
      const sc = evaluate(seven);
      if (sc > best) {
        best = sc;
        ties = 1;
      } else if (sc === best) ties++;
    }
    if (mine > best) share += 1;
    else if (mine === best) share += 1 / (ties + 1);
  }
  return share / SAMPLES;
}

const hu = [];
const multi = [];
for (let k = 0; k < 169; k++) {
  const info = classInfo(k);
  const hole = info.pair
    ? [makeCard(info.hi, 0), makeCard(info.lo, 1)]
    : info.suited
      ? [makeCard(info.hi, 0), makeCard(info.lo, 0)]
      : [makeCard(info.hi, 0), makeCard(info.lo, 1)];
  hu.push(+equity(hole, 1).toFixed(4));
  multi.push(+equity(hole, 3).toFixed(4));
}

const out = `// Generated by scripts/gen_preflop.js. Do not edit by hand.
// All-in equity for each of the 169 hand classes (see engine/hands.js for the index order).
export const EQ_HEADS_UP = ${JSON.stringify(hu)};
export const EQ_FOUR_WAY = ${JSON.stringify(multi)};
`;
writeFileSync(new URL('../src/data/preflop.js', import.meta.url), out);
